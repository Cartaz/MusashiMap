export const messageKeys = language => Object.keys(messages[language] ?? {});

const STORAGE_KEY = "musashimap:language";
const subscribers = new Set();
let currentLanguage = DEFAULT_LANGUAGE;

const supported = value => LANGUAGES.includes(value) ? value : null;

// Stored choice first, then the browser's preferred languages; Italian is the
// project's original language and the fallback.
export function detectLanguage({ storage = globalThis.localStorage, languages = globalThis.navigator?.languages } = {}) {
  try {
    const stored = supported(storage?.getItem(STORAGE_KEY));
    if (stored) return stored;
  } catch {
    // Storage can be unavailable; fall through to the browser preference.
  }
  for (const tag of languages ?? []) {
    const match = supported(String(tag).toLowerCase().split("-")[0]);
    if (match) return match;
  }
  return DEFAULT_LANGUAGE;
}

export function getLanguage() {
  return currentLanguage;
}

export function setLanguage(language, { persist = true } = {}) {
  const next = supported(language);
  if (!next || next === currentLanguage) return false;
  currentLanguage = next;
  if (persist) {
    try {
      globalThis.localStorage?.setItem(STORAGE_KEY, next);
    } catch {
      // Persistence is optional.
    }
  }
  for (const subscriber of subscribers) subscriber(next);
  return true;
}

export function subscribeLanguage(subscriber) {
  subscribers.add(subscriber);
  return () => subscribers.delete(subscriber);
}

export function t(key, params = {}, language = currentLanguage) {
  const message = messages[language]?.[key] ?? messages[DEFAULT_LANGUAGE][key];
  if (message === undefined) return key;
  return typeof message === "function" ? message(params) : message;
}

// Static markup declares its text with data-i18n="key" and its attributes with
// data-i18n-attr="attribute:key;attribute:key".
export function translateDocument(root = globalThis.document) {
  if (!root) return;
  const html = root.documentElement;
  if (html) html.lang = currentLanguage;
  root.querySelector?.('meta[name="description"]')?.setAttribute("content", t("meta.description"));
  for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll("[data-i18n-attr]")) {
    for (const pair of node.dataset.i18nAttr.split(";")) {
      const [attribute, key] = pair.split(":").map(part => part.trim());
      if (attribute && key) node.setAttribute(attribute, t(key));
    }
  }
}
